import { type HybridObject } from 'react-native-nitro-modules'
import type { Mmfile, EncryptedMmfile } from './Mmfile.nitro'

export interface ReadDirItem {
  mtime: number;          // The last modified date of the file (seconds since epoch)
  name: string;           // The name of the item
  path: string;           // The absolute path to the item
  size: number;           // Size in bytes
  isFile: boolean;        // Is the item just a file?
  isDirectory: boolean;   // Is the item a directory?
}

export interface MmfilePackage extends HybridObject<{ ios: 'c++', android: 'c++' }> {
  baseDirectory: string;

  openMmfile(path: string, readOnly?: boolean): Mmfile;
  openEncryptedMmfile(path: string, key: ArrayBuffer, readOnly?: boolean): EncryptedMmfile;

  fileExists(path: string): boolean;
  getFileSize(path: string): number;
  getEncryptedFileSize(path: string): number;

  /**
   * True if the path is an encrypted file written by react-native-mmfile <= 1.6.0, which
   * generated the data key and IV with a general-purpose PRNG seeded with 32 bits. Their
   * data key can be recovered from the header alone, so rewrite them with
   * `rekeyEncryptedFile`. False for current files and anything that is not an encrypted
   * file. Reads only the header, needs no key, and works on files that are open.
   */
  isLegacyEncryptedFile(path: string): boolean;

  /**
   * Re-encrypts an encrypted file under a data key and IV newly generated by the OS
   * random number generator. `key` stays the same. The new content is written to a temporary file under `baseDirectory` and
   * renamed over the original, so an interruption leaves either the old or the new file.
   * The modification time is preserved.
   *
   * @returns true if the file was rewritten, false if it was empty or its keys already
   * come from the OS random number generator (pass `force` to rewrite those as well)
   * @throws if the file is missing, not an encrypted file, `key` is wrong, or the file
   * is currently open in this process
   */
  rekeyEncryptedFile(path: string, key: ArrayBuffer, force?: boolean): boolean;

  readDir(path: string): Promise<ReadDirItem[]>
  readDirSync(path: string): ReadDirItem[]

  unlink(path: string): Promise<void>;
  unlinkSync(path: string): void;
}
